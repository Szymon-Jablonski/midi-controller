void send_midi_note_on(uint8_t note, uint8_t velocity)
{
	uint8_t const cable_num = 0;
	uint8_t const channel = 0;

	uint8_t msg[3] = {
			0x90 | channel,
			note,
			velocity
	};

	tud_midi_stream_write(cable_num, msg, 3);
}

void send_midi_note_off(uint8_t note)
{
	uint8_t const cable_num = 0;
	uint8_t const channel = 0;

	uint8_t msg[3] = {
			0x80 | channel,
			note,
			0
	};

	tud_midi_stream_write(cable_num, msg, 3);
}


uint8_t notes[8] = {60, 62, 64, 65, 67, 69, 71, 72};
uint32_t last_ticks[8] = {0};
uint32_t debounce_delay = 15; // in ms


void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
	uint8_t pin_number = __builtin_ctz(GPIO_Pin); //convert from HAL bitmask to index

	if ((ticks - last_ticks[pin_number]) > debounce_delay)
	{
		GPIO_PinState state = HAL_GPIO_ReadPin(GPIOE, GPIO_Pin);

		if (state == GPIO_PIN_SET)
		{
			send_midi_note_off(notes[pin_number]);
		}
		else
		{
			send_midi_note_on(notes[pin_number], 127);
		}
		last_ticks[pin_number] = ticks;
	}
}

